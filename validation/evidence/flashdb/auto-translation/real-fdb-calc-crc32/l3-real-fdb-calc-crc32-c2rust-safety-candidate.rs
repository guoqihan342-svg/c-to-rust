pub fn fdb_calc_crc32(mut crc: uint32_t, buf: &[uint8_t]) -> uint32_t {
    crc = crc ^ !(0 as uint32_t);
    for byte in buf {
        crc = crc32_table[((crc ^ *byte as uint32_t) & 0xff as uint32_t) as usize]
        ^ crc >> 8 as ::core::ffi::c_int;
    }
    return crc ^ !(0 as uint32_t);
}
